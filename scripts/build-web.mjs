/**
 * Builds the installable web app.
 *
 * Expo's web export produces a bare index.html with no PWA metadata and no
 * service worker, and offers no hook to customise that HTML outside Expo Router.
 * So the export runs first and this script decorates the output: it injects the
 * manifest link and the Apple-specific tags that "Add to Home Screen" reads, then
 * generates a service worker that precaches the exact hashed filenames this build
 * produced, which is what makes the app launch offline.
 */
import { execSync } from 'child_process';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'fs';
import { join, relative } from 'path';

const DIST = 'dist';

console.log('› exporting web build');
execSync('npx expo export --platform web --clear', { stdio: 'inherit' });

/** Every emitted file, as a root-relative URL path. */
function walk(dir) {
  const out = [];
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) out.push(...walk(full));
    else out.push('/' + relative(DIST, full).split(/[\\/]/).join('/'));
  }
  return out;
}

const files = walk(DIST);
// metadata.json is Expo build bookkeeping, not something the page ever fetches.
const precache = files.filter((f) => f !== '/metadata.json');
const bundle = files.find((f) => f.startsWith('/_expo/static/js/web/'));

// Tie the cache name to the bundle hash so a new build supersedes the old cache
// instead of serving a stale shell forever.
const version = bundle ? bundle.replace(/.*index-([a-f0-9]+)\.js/, '$1').slice(0, 12) : Date.now();

const HEAD = `
    <link rel="manifest" href="/manifest.webmanifest" />
    <meta name="theme-color" content="#fcfcfb" />
    <meta name="description" content="Muscle heat map for StrengthLog CSV exports" />
    <!-- iOS reads these when the page is added to the home screen. Without
         apple-mobile-web-app-capable it opens in a Safari chrome instead of
         standalone, and without apple-touch-icon it screenshots the page. -->
    <meta name="apple-mobile-web-app-capable" content="yes" />
    <meta name="apple-mobile-web-app-status-bar-style" content="default" />
    <meta name="apple-mobile-web-app-title" content="Styrklog" />
    <link rel="apple-touch-icon" href="/icons/apple-touch-icon.png" />`;

const SW_REGISTER = `
    <script>
      if ('serviceWorker' in navigator) {
        window.addEventListener('load', function () {
          navigator.serviceWorker.register('/sw.js').catch(function () {
            /* Offline launch is a bonus; the app still works without it. */
          });
        });
      }
    </script>`;

let html = readFileSync(join(DIST, 'index.html'), 'utf8');
// viewport-fit=cover lets the layout reach under the notch in standalone mode.
html = html.replace(
  'content="width=device-width, initial-scale=1, shrink-to-fit=no"',
  'content="width=device-width, initial-scale=1, shrink-to-fit=no, viewport-fit=cover"',
);
html = html.replace('</head>', `${HEAD}\n  </head>`);
html = html.replace('</body>', `${SW_REGISTER}\n  </body>`);
writeFileSync(join(DIST, 'index.html'), html);

const sw = `// Generated by scripts/build-web.mjs — do not edit by hand.
const CACHE = 'styrklog-${version}';
const PRECACHE = ${JSON.stringify(precache, null, 2)};

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)).then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const { request } = event;
  if (request.method !== 'GET') return;

  // Navigations always resolve to the app shell: this is a single-page app, and
  // a cached shell is what lets it open with no network at all.
  if (request.mode === 'navigate') {
    event.respondWith(
      fetch(request).catch(() => caches.match('/index.html').then((r) => r || Response.error())),
    );
    return;
  }

  event.respondWith(
    caches.match(request).then(
      (cached) =>
        cached ||
        fetch(request).then((response) => {
          if (response.ok && new URL(request.url).origin === self.location.origin) {
            const copy = response.clone();
            caches.open(CACHE).then((cache) => cache.put(request, copy));
          }
          return response;
        }),
    ),
  );
});
`;

writeFileSync(join(DIST, 'sw.js'), sw);

console.log(`\n› injected PWA metadata into ${DIST}/index.html`);
console.log(`› wrote ${DIST}/sw.js — cache "styrklog-${version}", ${precache.length} precached files`);
